"""Builds firmware/config_page_gz.h: the /config page as one gzip stream (R6, saves about 4 KB of flash).

The source of the page is firmware/config_page.h (CONFIG_PAGE, the body), the document head and tail come from
PAGE_HEAD and PAGE_TAIL in firmware/safety.cpp, so the page looks exactly as before. Browsers decode it with
Content-Encoding: gzip. Run `python tools/gen_config_gz.py` after changing config_page.h or PAGE_HEAD, and
`python tools/gen_config_gz.py --verify` (CI) checks that the committed header still decodes to the source.
"""
import gzip, io, os, re, sys, zlib

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
FW = os.path.join(ROOT, "firmware")
OUT = os.path.join(FW, "config_page_gz.h")


def source_html():
    safety = open(os.path.join(FW, "safety.cpp"), encoding="utf-8").read()
    head = re.search(r'PAGE_HEAD\[\] PROGMEM = R"HTML\((.*?)\)HTML";', safety, re.S).group(1)
    tail = re.search(r'PAGE_TAIL\[\] PROGMEM = "(.*?)";', safety).group(1)
    page = open(os.path.join(FW, "config_page.h"), encoding="utf-8").read()
    body = re.search(r'CONFIG_PAGE\[\] PROGMEM = R"HTML\((.*?)\)HTML";', page, re.S).group(1)
    html = (head + body + tail).encode("utf-8")
    return html


def build():
    html = source_html()
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0) as f:
        f.write(html)
    return html, buf.getvalue()


def render(gz):
    lines = []
    for i in range(0, len(gz), 16):
        lines.append("  " + ",".join(f"0x{v:02x}" for v in gz[i:i + 16]) + ",")
    return ("// GENERATED by tools/gen_config_gz.py from config_page.h and PAGE_HEAD/PAGE_TAIL in safety.cpp - do not edit.\n"
            "#pragma once\n#include <Arduino.h>\n"
            f"#define CONFIG_PAGE_GZ_LEN {len(gz)}\n"
            f"static const unsigned char CONFIG_PAGE_GZ[CONFIG_PAGE_GZ_LEN] PROGMEM = {{\n" + "\n".join(lines) + "\n};\n")


def main():
    html, gz = build()
    if "--verify" in sys.argv:
        text = open(OUT, encoding="utf-8").read()
        m = re.search(r"CONFIG_PAGE_GZ_LEN (\d+)", text)
        data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", text.split("PROGMEM = {", 1)[1]))
        if not m or int(m.group(1)) != len(data):
            sys.exit("config_page_gz.h: length does not match its data")
        if zlib.decompress(data, 16 + zlib.MAX_WBITS) != html:
            sys.exit("config_page_gz.h is out of date: run python tools/gen_config_gz.py")
        print(f"config_page_gz.h ok ({len(data)} bytes gzip for {len(html)} bytes of page)")
        return
    open(OUT, "w", encoding="utf-8").write(render(gz))
    print(f"wrote firmware/config_page_gz.h: {len(gz)} bytes for {len(html)} bytes of page")


if __name__ == "__main__":
    main()
