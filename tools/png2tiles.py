"""Converts the PNG sheets in assets/src/ into 4bpp C arrays for the game core.

    python tools/png2tiles.py

Rules: every pixel must be one of the 16 palette colours in tools/palette.py
(magenta = transparent). Sheets are cut into 16x16 cells, left-to-right,
top-to-bottom. Each distinct cell becomes 128 bytes (2 pixels per byte, high
nibble = left pixel); identical cells (placeholders) are stored once and found
through GC_<NAME>_MAP, read with the GC_<NAME>(id) macro. Output: lib/gamecore/src/assets_gen.h
"""
import os
import sys
from PIL import Image

from palette import PALETTE, RGB_TO_INDEX, rgb565
from font5x7 import GLYPHS, FIRST, LAST

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = os.path.join(ROOT, "assets", "src")
OUT = os.path.join(ROOT, "lib", "gamecore", "src", "assets_gen.h")

SHEETS = [
    # (file, C name)
    ("tiles.png", "TILES"),
    ("chars.png", "CHARS"),
    ("items.png", "ITEMS"),
]


def cut(path):
    img = Image.open(path).convert("RGB")
    w, h = img.size
    if w % 16 or h % 16:
        sys.exit(f"{path}: size {w}x{h} is not a multiple of 16")
    cells = []
    for ty in range(h // 16):
        for tx in range(w // 16):
            data = bytearray()
            for y in range(16):
                for x in range(0, 16, 2):
                    px = []
                    for dx in (0, 1):
                        rgb = img.getpixel((tx * 16 + x + dx, ty * 16 + y))
                        if rgb not in RGB_TO_INDEX:
                            sys.exit(f"{path}: pixel ({tx*16+x+dx},{ty*16+y}) colour {rgb} is not in the palette")
                        px.append(RGB_TO_INDEX[rgb])
                    data.append((px[0] << 4) | px[1])
            cells.append(bytes(data))
    return cells, w // 16, h // 16


def c_bytes(b, indent="  "):
    lines = []
    for i in range(0, len(b), 16):
        lines.append(indent + ",".join(f"0x{v:02x}" for v in b[i:i + 16]) + ",")
    return "\n".join(lines)


def main():
    out = [
        "// GENERATED by tools/png2tiles.py - do not edit by hand.",
        "#pragma once",
        '#include "platform.h"',
        "",
        "// Every table is DEFINED once: gamecore.cpp defines GC_ASSETS_DEFINE before including this file.",
        "// All other files only see the extern declarations (one copy in the firmware, not one per .cpp).",
        "// The section attribute (PROGMEM) belongs to the definitions only.",
        "extern const uint16_t GC_PALETTE[16];",
    ]
    defs = [
        "#ifdef GC_ASSETS_DEFINE",
        "const uint16_t GC_PALETTE[16] GC_ROM_ATTR = {",
        "  " + ",".join(f"0x{rgb565(rgb):04x}" for _, _, rgb in PALETTE),
        "};",
        "",
    ]
    for fname, cname in SHEETS:
        cells, cols, rows = cut(os.path.join(SRC, fname))
        # Identical cells (placeholders) are stored once: GC_<NAME>_MAP[id] -> unique index.
        uniq, index = [], []
        for c in cells:
            if c not in uniq:
                uniq.append(c)
            index.append(uniq.index(c))
        assert len(uniq) <= 256
        out.append(f"// {fname}: {cols}x{rows} cells, {len(uniq)} distinct")
        out.append(f"#define GC_{cname}_COUNT {len(cells)}")
        out.append(f"#define GC_{cname}_COLS {cols}")
        out.append(f"extern const uint8_t GC_{cname}_DATA[{len(uniq)}][128];")
        out.append(f"extern const uint8_t GC_{cname}_MAP[{len(cells)}];")
        out.append(f"#define GC_{cname}(id) (GC_{cname}_DATA[GC_RD8(&GC_{cname}_MAP[(id)])])")
        defs.append(f"const uint8_t GC_{cname}_DATA[{len(uniq)}][128] GC_ROM_ATTR = {{")
        for i, c in enumerate(uniq):
            defs.append(f" {{ // distinct {i}")
            defs.append(c_bytes(c))
            defs.append(" },")
        defs.append("};")
        defs.append(f"const uint8_t GC_{cname}_MAP[{len(cells)}] GC_ROM_ATTR = {{")
        defs.append(c_bytes(bytes(index)))
        defs.append("};")
        defs.append("")

    n = LAST - FIRST + 1
    out.append(f"#define GC_FONT_FIRST {FIRST}")
    out.append(f"#define GC_FONT_LAST {LAST}")
    out.append(f"extern const uint8_t GC_FONT[{n}][7];")
    defs.append(f"const uint8_t GC_FONT[{n}][7] GC_ROM_ATTR = {{")
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        rows = GLYPHS.get(ch, GLYPHS["?"] if ch != " " else GLYPHS[" "])
        vals = []
        for r in rows:
            assert len(r) == 5, (ch, r)
            v = 0
            for i, c in enumerate(r):
                if c == "#":
                    v |= 0x10 >> i
            vals.append(v)
        label = ch if ch not in "\\" else "backslash"
        defs.append("  {" + ",".join(f"0x{v:02x}" for v in vals) + f"}}, // '{label}'")
    defs.append("};")
    defs.append("#endif  // GC_ASSETS_DEFINE")
    defs.append("")
    out.append("")
    out.extend(defs)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
